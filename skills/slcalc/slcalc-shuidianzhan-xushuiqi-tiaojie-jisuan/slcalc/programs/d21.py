def parse(data):
    """解析输入。data：dict | .INT 文件路径。兼容说明书算例中的 K=0 占位（24 个数）。"""
    if isinstance(data, dict):
        p = dict(data)
        for k in ("M", "N"):
            if k in p:
                p[k] = int(round(p[k]))
        return p
    nums = read_numbers(data)
    n = len(nums)
    if n == 24:                       # 说明书算例：M,K,N,... 含 K=0 占位
        nums = [nums[0]] + nums[2:]
        n = len(nums)
    if n != 23:
        raise ValueError("D-21 输入数据个数 %d 应为 23（或 24 含 K 占位）" % n)
    p = dict(zip(_KEYS, nums))
    p["M"] = int(round(p["M"]))
    p["N"] = int(round(p["N"]))
    return p


