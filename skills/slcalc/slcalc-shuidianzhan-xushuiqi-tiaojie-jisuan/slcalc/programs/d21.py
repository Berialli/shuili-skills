def constants(p):
    AL, T = p["AL"], p["T"]
    AN1, AK1 = p["AN1"], p["AK1"]
    D1, D2, D3, D5, D0 = p["D1"], p["D2"], p["D3"], p["D5"], p["D0"]
    A1 = K_AREA_A1 * D1 * D1
    A2 = K_AREA * D2 * D2
    A0 = K_AREA * D0 * D0
    A3 = K_AREA * D3 * D3
    A4 = A0 - A3
    lam = 8.0 * G_MANN * AN1 * AN1 / ((D1 / 4.0) ** (1.0 / 3.0))
    AK2 = lam * AL / D1
    AK = AK2 + AK1
    C1 = T * G * A1 / AL
    C2 = T / (2.0 * A0)
    C5 = p["AM1"] * A2 * math.sqrt(2.0 * G_C5)
    C6 = p["AM2"] * A2 * math.sqrt(2.0 * G_C6)
    C7 = p["AM0"] * PI * D5 * math.sqrt(2.0 * G_C7)
    Cc = p["AM"] * PI * D5 * math.sqrt(2.0 * G_C)
    return {"A1": A1, "A2": A2, "A0": A0, "A3": A3, "A4": A4,
            "AK2": AK2, "AK": AK, "C1": C1, "C2": C2, "C3": C3_PRINT,
            "C5": C5, "C6": C6, "C7": C7, "C": Cc,
            "C8": 1.0 / A2, "C9": 1.0 / A4}


