# 计算
# ============================================================

def _simulate(case, p, k):
    """RK4，步长 T（原著口径）。case='drop' 甩全荷(100%→0%)、'add' 半荷→满荷。"""
    g, L, A1 = G, p["AL"], k["A1"]
    T, T0, D5 = p["T"], p["T0"], p["D5"]
    Z1 = p["Z1"]
    Fc, Fp = F_RISER_EFF, F_OUTER_EFF
    C5 = SK_ORIF_P * k["C5"]
    C6 = SK_ORIF_M * k["C6"]
    C7, C8 = k["C7"], k["C"]
    AK = k["AK"]
    if case == "drop":
        Q0 = p["AQ0"]
    else:
        Q0 = p["AQ4"]

    def Q_t(t):
        if case == "drop":
            return p["AQ0"] * max(0.0, 1.0 - t / T0)
        return p["AQ4"] + (p["AQ0"] - p["AQ4"]) * min(1.0, max(0.0, t / T0))

    def deriv(Zc, Zp, Qe, t):
        dz = Zc - Zp
        Qc = (C5 * math.sqrt(dz)) if dz >= 0.0 else (-C6 * math.sqrt(-dz))
        if Zc > Z1 and Zp > Z1:
            QB = 0.0
        elif Zc > Z1:
            QB = C7 * (Zc - Z1) ** 1.5
        elif Zp > Z1:
            QB = -C8 * (Zp - Z1) ** 1.5
        else:
            QB = 0.0
        dQe = -(g * A1 / L) * Zc - AK * Qe * abs(Qe) / (2.0 * L * A1)
        return dQe, (Qe - Q_t(t) - Qc - QB) / Fc, (Qc + QB) / Fp

    Zc = Zp = -AK * Q0 * Q0 / (2.0 * g * A1 * A1)
    Qe = Q0
    t = 0.0
    out = []
    for _ in range(int(p["N"])):
        h = T
        k1 = deriv(Zc, Zp, Qe, t)
        k2 = deriv(Zc + h / 2 * k1[1], Zp + h / 2 * k1[2], Qe + h / 2 * k1[0], t + h / 2)
        k3 = deriv(Zc + h / 2 * k2[1], Zp + h / 2 * k2[2], Qe + h / 2 * k2[0], t + h / 2)
        k4 = deriv(Zc + h * k3[1], Zp + h * k3[2], Qe + h * k3[0], t + h)
        Zc += h / 6.0 * (k1[1] + 2 * k2[1] + 2 * k3[1] + k4[1])
        Zp += h / 6.0 * (k1[2] + 2 * k2[2] + 2 * k3[2] + k4[2])
        Qe += h / 6.0 * (k1[0] + 2 * k2[0] + 2 * k3[0] + k4[0])
        t += h
        out.append(Zc)
    return out


def compute(p):
    k = constants(p)
    sx = p["SX"]
    c1 = _simulate("drop", p, k)
    c2 = _simulate("add", p, k)
    if sx >= 0:
        base1, base2 = p["Z0"], p["Z"]
    else:
        base1, base2 = p["Z"], p["Z0"]
    return {"程序": PROGRAM_ID, "标题": TITLE, "作者": AUTHOR,
            "输入": p, "常数": k, "工况1": c1, "工况2": c2,
            "基准1": base1, "基准2": base2}


