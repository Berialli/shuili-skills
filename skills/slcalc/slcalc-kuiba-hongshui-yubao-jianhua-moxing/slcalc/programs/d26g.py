# ============================================================
# 数值口径
# ============================================================

def r2(x):
    """VB6 Format(x,"0.00") 口径：十进制四舍五入（half away from zero）。"""
    from decimal import Decimal, ROUND_HALF_UP
    if x != x or x in (float("inf"), float("-inf")):
        return x
    return float(Decimal(x).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


def chain(x):
    """桩号格式：1234.5 -> '1+234.50'（km + 3 位 m + .2f）。"""
    km = int(abs(x) // 1000)
    m = abs(x) - km * 1000
    s = "%d+%06.2f" % (km, m)
    return ("-" + s) if x < 0 else s


# ============================================================
# 水力要素
# ============================================================

def pipe_const(ntype):
    """返回管材常数 (f, m, b)；类型 10 抛错（原著未列式）。"""
    c = PIPE_TABLE.get(int(ntype))
    if c is None:
        raise ValueError(
            "管壁材料类型 %s 无可用公式：原著说明书第 10 类（旧钢管/铸铁管分段公式）"
            "只列名未给式（「公式可参考该规范」），无权威数据可反演，不猜测实现。"
            % (ntype,))
    return c


def unit_loss(q, d, ntype):
    """单位管长沿程水头损失 i = f·Q^m/d^b  (m/m)。"""
    f, m, b = pipe_const(ntype)
    return f * (q ** m) / (d ** b)


def seg_loss(q, d, ntype, length, k):
    """本段水头损失 h = i·L·(1 + K·LOCAL_K_COEF)  (m)。"""
    return unit_loss(q, d, ntype) * length * (1.0 + k * LOCAL_K_COEF)


def velocity(q, d):
    """流速 V = Q/(π D²/4)  (m/s)。"""
    return q / (PI * d * d / 4.0)


# ============================================================
# 解析
# ============================================================

def _field(line):
    return [t.strip() for t in line.split(",")]


def parse(data):
    """
    解析输入。data：dict（直接返回）| .INT 文件路径（GBK）。

    返回 dict：
      {"工程名","M","QZ","Z0","K0",
       "节点":[{"i","name","x","Q","D","N","K","GD"}, ...]}（共 M+1 个）
    """
    if isinstance(data, dict):
        return data

    lines = [ln.strip() for ln in read_lines(data)]
    lines = [ln for ln in lines if ln]
    if len(lines) < 2:
        raise ValueError("D-26G 输入数据不足：至少需 1 行控制数据 + 1 行分段数据")

    head = _field(lines[0])
    if len(head) < 5:
        raise ValueError("D-26G 控制数据字段不足（需 工程名,M,QZ,Z0,K0，实得 %d）" % len(head))
    name = head[0]
    try:
        M = int(float(head[1]))
        QZ = float(head[2])
        Z0 = float(head[3])
        K0 = int(float(head[4]))
    except ValueError:
        raise ValueError("D-26G 控制数据数值解析失败：%r" % (lines[0],))
    if K0 not in (1, 2):
        raise ValueError("D-26G 计算起始信息只能为 1（上游→下游）或 2（下游→上游），实得 %s" % K0)
    if M < 1:
        raise ValueError("D-26G 管道分段数 M 必须 ≥ 1，实得 %d" % M)

    nodes = []
    for j, ln in enumerate(lines[1:1 + M + 1]):
        fl = _field(ln)
        if len(fl) < 6:
            raise ValueError("D-26G 第 %d 行分段数据字段不足（需 桩号,Q,D,N,K,GD）：%r" % (j + 1, ln))
        nodes.append({
            "i": j,
            "name": "",
            "x": float(fl[0]),
            "Q": float(fl[1]),
            "D": float(fl[2]),
            "N": int(float(fl[3])),
            "K": float(fl[4]),
            "GD": float(fl[5]),
        })
    if len(nodes) != M + 1:
        raise ValueError("D-26G 分段数据行数不符：M=%d 需 %d 行，实得 %d 行" % (M, M + 1, len(nodes)))

    return {"工程名": name, "M": M, "QZ": QZ, "Z0": Z0, "K0": K0, "节点": nodes}


# ============================================================
# 计算
# ============================================================

def compute(params):
    """执行 D-26G 计算：逐段推算水压高程 + 明满流钳制。"""
    nodes = params["节点"]
    M = params["M"]
    K0 = params["K0"]
    order = list(range(M + 1)) if K0 == 1 else list(range(M, -1, -1))

    Z = [None] * (M + 1)
    loss = [0.0] * (M + 1)
    span = [0.0] * (M + 1)
    clamped = [False] * (M + 1)
    Z[order[0]] = params["Z0"]

    for n in range(1, len(order)):
        j, p = order[n], order[n - 1]
        nd = nodes[j]
        L = abs(nd["x"] - nodes[p]["x"])
        span[j] = L
        h = seg_loss(nd["Q"], nd["D"], nd["N"], L, nd["K"])
        loss[j] = h
        z = Z[p] - h if K0 == 1 else Z[p] + h
        if z - nd["GD"] < 0.0:
            # 明满流判别：令管内水深 = 管内径，水压高程 = 管内壁顶
            z = nd["GD"] + nd["D"]
            clamped[j] = True
        Z[j] = z

    rows = []
    for j, nd in enumerate(nodes):
        v = velocity(nd["Q"], nd["D"])
        gd = nd["GD"]
        rows.append({
            "i": j, "name": nd["name"], "x": nd["x"], "Q": nd["Q"], "D": nd["D"],
            "N": nd["N"], "K": nd["K"], "GD": gd,
            "距离": span[j],
            "V": v, "Vh": v * v / (2.0 * G),
            "损失": loss[j], "Z": Z[j], "GY": Z[j] - gd,
            "钳制": clamped[j],
        })

    return {
        "程序": PROGRAM_ID,
        "标题": TITLE,
        "作者": AUTHOR,
        "工程名": params["工程名"],
        "M": M,
        "QZ": params["QZ"],
        "Z0": params["Z0"],
        "K0": K0,
        "节点": rows,
        "钳制节点": [r["i"] for r in rows if r["钳制"]],
    }


# ============================================================
# 输出（逐字复刻原著 .OUT 版式）
# ============================================================

_HEAD14 = "       终止                    管壁               水头    水压    管底    管底"
_HEAD15 = "序号           流量      内径  类型 流速 流速水头 损失    高程    高程    水头"
_HEAD16 = " I     桩号      Q         D     N    V   V^2/2g   和       Z      GD      GY "


def _row(r):
    s = "%3d" % (r["i"] + 1 - 1)
    s += "  %-8s" % chain(r["x"])
    s += "  %8.6f" % r["Q"]
    s += "  %5.3f" % r["D"]
    s += "  %2d" % r["N"]
    if r["钳制"]:
        s += "(%5.2f" % r2(r["V"])
    else:
        s += "  %4.2f" % r2(r["V"])
    s += "  %5.2f" % r2(r["Vh"])
    s += "  %5.2f" % r2(r["损失"])
    if r["钳制"]:
        s += ")%8.2f" % r2(r["Z"])
    else:
        s += "  %7.2f" % r2(r["Z"])
    s += " %7.2f" % r2(r["GD"])
    s += "  %6.2f" % r2(r["GY"])
    return s


def render(params, result, out_path=None):
    """生成原著风格文本计算书（.OUT）。返回自第 2 行（空行）起的文本。"""
    L = []
    L.append("")
    L.append(" " + "*" * 76)
    L.append(" **********                 供水管道水力学计算书                   **********")
    L.append(" " + "*" * 76)
    L.append("")
    L.append(" " * 24 + "工程名  " + result["工程名"])
    L.append("")
    L.append(" " * 24 + "管道分段数 M= %d " % result["M"])
    L.append(" " * 4 + "起始桩号:  " + chain(result["QZ"]) + " " * 25
             + "起始水位  Zo=" + ("%.2f" % r2(result["Z0"])))
    L.append("")
    L.append(" " * 29 + "分段计算结果")
    L.append(" " * 29 + "============")
    L.append("")
    L.append(_HEAD14)
    L.append(_HEAD15)
    L.append(_HEAD16)
    L.append("")
    for r in result["节点"]:
        L.append(_row(r))
    return "\n".join(L)


def run(data, out_txt=None, out_json=None, fmt="text"):
    """统一入口。data：INT 文件路径 | dict。"""
    params = parse(data)
    result = compute(params)
    text = render(params, result)
    if out_txt:
        write_out(out_txt, text)
    if out_json:
        write_json(out_json, result)
    return result, text


if __name__ == "__main__":
    import sys
    _res, _txt = run(sys.argv[1] if len(sys.argv) > 1 else None)
