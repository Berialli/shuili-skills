_KEYS = ["M", "N", "AN1", "AK1", "T", "T0", "AL", "AQ0", "AQ4",
         "D1", "D2", "D0", "A6", "A7", "AK0", "AK3", "Z0", "Z", "ST", "SX"]


def parse(data):
    """解析输入。data：dict | .INT 文件路径。兼容说明书算例中的 K=0 占位。"""
    if isinstance(data, dict):
        p = dict(data)
        for k in ("M", "N"):
            if k in p:
                p[k] = int(round(p[k]))
        return p
    nums = read_numbers(data)
    n = len(nums)
    if n < 20:
        raise ValueError("D-20 输入数据过少（%d 个数）" % n)
    if n == 21:            # 说明书算例：M,K,N,... 多一个 K=0
        nums = [nums[0]] + nums[2:]
    elif n != 20:
        raise ValueError("D-20 输入数据个数 %d 应为 20（或 21 含 K 占位）" % n)
    p = dict(zip(_KEYS, nums))
    p["M"] = int(round(p["M"]))
    p["N"] = int(round(p["N"]))
    return p


