def constants(p):
    """中间成果常数（逐位复刻原著打印口径）。"""
    AL, T = p["AL"], p["T"]
    AN1, AK1 = p["AN1"], p["AK1"]
    D1, D2, D0 = p["D1"], p["D2"], p["D0"]
    A1 = K_AREA_A1 * D1 * D1
    A2 = K_AREA * D2 * D2
    Fb = K_AREA * D0 * D0
    R = D1 / 4.0
    lam = 8.0 * G_MANN * AN1 * AN1 / (R ** (1.0 / 3.0))
    AK = lam * AL / D1 + AK1
    TT = 2.0 * math.pi * math.sqrt(AL * Fb / (G_TT * A1))
    C1 = T * G * A1 / AL
    C2 = T / (2.0 * Fb)
    C3 = 3.0e-5
    return {"A1": A1, "A2": A2, "F": Fb, "lam": lam, "AK": AK,
            "TT": TT, "C1": C1, "C2": C2, "C3": C3}


def _simulate(Qa, Qb, abrupt, p, k, nsteps):
    """
    数值积分（RK4，子步 T/8，收敛解）。
      Qa：初始引用流量；Qb：末态引用流量
      abrupt=True：Q_t 立刻跳到 Qb（突增/突降）；False：按 T0 线性过渡
    """
    g, L, A1 = G, p["AL"], k["A1"]
    Fb, AK = k["F"], k["AK"]
    T, T0 = p["T"], p["T0"]
    A6, A7, AK0, AK3 = p["A6"], p["A7"], p["AK0"], p["AK3"]
    kin = AK0 / (2.0 * g * A6 * A6)
    kout = AK3 / (2.0 * g * A7 * A7)

    def Q_t(t):
        if abrupt:
            return Qb
        if t >= T0:
            return Qb
        return Qa + (Qb - Qa) * (t / T0)

    def hw(qe):
        return AK * qe * abs(qe) / (2.0 * g * A1 * A1)

    def hc(qc):
        return (kin if qc >= 0.0 else kout) * qc * abs(qc)

    Qe = Qa
    Z = -hw(Qe)
    h = T / 8.0
    t = 0.0
    out = []
    for _ in range(nsteps):
        for _ in range(8):
            def deriv(qe, zz, tt):
                return (-(g * A1 / L) * (zz + hw(qe) + hc(qe - Q_t(tt))),
                        (qe - Q_t(tt)) / Fb)
            k1 = deriv(Qe, Z, t)
            k2 = deriv(Qe + h / 2 * k1[0], Z + h / 2 * k1[1], t + h / 2)
            k3 = deriv(Qe + h / 2 * k2[0], Z + h / 2 * k2[1], t + h / 2)
            k4 = deriv(Qe + h * k3[0], Z + h * k3[1], t + h)
            Qe += h / 6.0 * (k1[0] + 2 * k2[0] + 2 * k3[0] + k4[0])
            Z += h / 6.0 * (k1[1] + 2 * k2[1] + 2 * k3[1] + k4[1])
            t += h
        out.append(Z)
    return out


def compute(p):
    """执行 D-20 计算，返回结构化结果 dict。"""
    N, T = p["N"], p["T"]
    k = constants(p)
    sx = p["SX"]
    case1 = _simulate(float(p["AQ0"]), 0.0, False, p, k, N)
    case2 = _simulate(float(p["AQ4"]), float(p["AQ0"]), True, p, k, N)
    # 基准水位：上游(SX=1) 工况1 用 Z0、工况2 用 Z；下游(SX=-1) 相反
    if sx >= 0:
        base1, base2 = p["Z0"], p["Z"]
    else:
        base1, base2 = p["Z"], p["Z0"]
    return {
        "程序": PROGRAM_ID, "标题": TITLE, "作者": AUTHOR,
        "输入": p, "常数": k,
        "工况1": case1, "工况2": case2,
        "基准1": base1, "基准2": base2,
    }


