K_AREA = 0.7854             # 本程序（含隧洞面积）统一用 0.7854
G_MANN = 9.811650570          # 由权威 AK2=1.15520 反演（5 位小数逐位命中）
C3_PRINT = 2.0e-5           # 二阶小量（原著打印值，不参与计算）


