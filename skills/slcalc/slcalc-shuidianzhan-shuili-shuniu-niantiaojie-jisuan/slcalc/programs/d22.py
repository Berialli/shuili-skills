_KEYS = ["M", "N", "AN1", "AK1", "T", "T0", "AL", "AQ0", "AQ4",
         "D1", "D0", "Z0", "Z", "ST", "SX", "D3", "D5", "Z1", "Z2"]


def parse(data):
    """解析输入。data：dict | .INT 文件路径。"""
    if isinstance(data, dict):
        p = dict(data)
        for k in ("M", "N"):
            if k in p:
                p[k] = int(round(p[k]))
        return p
    nums = read_numbers(data)
    n = len(nums)
    if n != 19:
        raise ValueError("D-22 输入数据个数 %d 应为 19" % n)
    p = dict(zip(_KEYS, nums))
    p["M"] = int(round(p["M"]))
    p["N"] = int(round(p["N"]))
    return p


# ============================================================
# 中间成果常数
# ============================================================

def constants(p):
    AL, T = p["AL"], p["T"]
    AN1, AK1 = p["AN1"], p["AK1"]
    D1, D0, D3, D5 = p["D1"], p["D0"], p["D3"], p["D5"]
    A1 = K_AREA * D1 * D1
    A0 = K_AREA * D0 * D0
    A3 = K_AREA * D3 * D3
    A5 = K_AREA * D5 * D5
    lam = 8.0 * G_MANN * AN1 * AN1 / ((D1 / 4.0) ** (1.0 / 3.0))
    AK2 = lam * AL / D1
    AK = AK2 + AK1
    C1 = T * G * A1 / AL
    C2 = T / (2.0 * A0)
    return {"A1": A1, "A0": A0, "A3": A3, "A5": A5, "AK2": AK2, "AK": AK,
            "C1": C1, "C2": C2, "C3": C3_PRINT}


# ============================================================
# 计算
# ============================================================

def _area(Z, p, k):
    """双室式变断面 F(Z)。"""
    if Z > p["Z2"]:
        return k["A0"]
    if Z > p["Z1"]:
        return k["A5"]
    return k["A0"] + k["A3"]


def _simulate(case, p, k):
    g, L, A1 = G, p["AL"], k["A1"]
    T, T0, AK = p["T"], p["T0"], k["AK"]
    Q0 = p["AQ0"] if case == "drop" else p["AQ4"]

    def Q_t(t):
        if case == "drop":
            return p["AQ0"] * max(0.0, 1.0 - t / T0)
        return p["AQ4"] + (p["AQ0"] - p["AQ4"]) * min(1.0, max(0.0, t / T0))

    def deriv(Z, Qe, t):
        dQe = -(g * A1 / L) * Z - AK * Qe * abs(Qe) / (2.0 * L * A1)
        return dQe, (Qe - Q_t(t)) / _area(Z, p, k)

    Z = -AK * Q0 * Q0 / (2.0 * g * A1 * A1)
    Qe = Q0
    t = 0.0
    out = []
    for _ in range(int(p["N"])):
        h = T
        k1 = deriv(Z, Qe, t)
        k2 = deriv(Z + h / 2 * k1[1], Qe + h / 2 * k1[0], t + h / 2)
        k3 = deriv(Z + h / 2 * k2[1], Qe + h / 2 * k2[0], t + h / 2)
        k4 = deriv(Z + h * k3[1], Qe + h * k3[0], t + h)
        Z += h / 6.0 * (k1[1] + 2 * k2[1] + 2 * k3[1] + k4[1])
        Qe += h / 6.0 * (k1[0] + 2 * k2[0] + 2 * k3[0] + k4[0])
        t += h
        out.append(Z)
    return out


def compute(p):
    k = constants(p)
    sx = p["SX"]
    c1 = _simulate("drop", p, k)
    c2 = _simulate("add", p, k)
    if sx >= 0:
        base1, base2 = p["Z0"], p["Z"]
    else:
        base1, base2 = p["Z"], p["Z0"]
    return {"程序": PROGRAM_ID, "标题": TITLE, "作者": AUTHOR,
            "输入": p, "常数": k, "工况1": c1, "工况2": c2,
            "基准1": base1, "基准2": base2}


